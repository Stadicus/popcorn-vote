import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const deployedOutput = resolve(here, '../website');
const arguments_ = process.argv.slice(2);
if (arguments_.some((argument) => argument !== '--check') || arguments_.length > 1)
	throw new Error('Usage: node docs/website-src/generate.mjs [--check]');
const checkOnly = arguments_[0] === '--check';
const output = checkOnly ? await mkdtemp(resolve(tmpdir(), 'popcorn-vote-website-')) : deployedOutput;
const template = await readFile(resolve(here, 'index.html'), 'utf8');
const mediaKitTemplate = await readFile(resolve(here, 'media-kit.html'), 'utf8');
const catalogue = JSON.parse(await readFile(resolve(here, 'messages.json'), 'utf8'));
const overrides = JSON.parse(await readFile(resolve(here, 'overrides.json'), 'utf8'));
const faqCatalogue = JSON.parse(await readFile(resolve(here, 'faq.json'), 'utf8'));
const locales = Object.entries(catalogue.locales);
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const generatedMarker = '<!-- Generated by docs/website-src/generate.mjs. Do not edit directly. -->';
const safeSlug = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
// `$` is rejected too: every use of these validated strings ends up as the
// replacement argument to String.replaceAll, where "$'", "$`", and "$$" are
// substitution patterns, not literal text.
const unsafeMarkup = /["<>&\\$]/u;
const reservedSlugs = new Set(['assets', 'media-kit']);

const fail = (message) => {
	throw new Error(`Website generation failed: ${message}`);
};
const requireSafeText = (value, label) => {
	if (typeof value !== 'string' || !value.trim()) fail(`${label} is empty`);
	const hasControlCharacter = [...value].some((character) => {
		const codePoint = character.codePointAt(0);
		return codePoint <= 0x1f || codePoint === 0x7f;
	});
	if (unsafeMarkup.test(value) || hasControlCharacter)
		fail(`${label} contains markup-significant characters`);
};
const localeDirectory = (slug) => {
	const directory = resolve(output, slug);
	if (!directory.startsWith(`${output}${sep}`)) fail(`locale slug escapes the output directory: ${slug}`);
	return directory;
};
const sourceMessages = catalogue.messages.en;
if (!Array.isArray(sourceMessages) || sourceMessages.length === 0)
	fail('English source messages are missing');
if (new Set(sourceMessages).size !== sourceMessages.length) fail('English source messages must be unique');
if (new Set(sourceMessages.map((message) => message.replace(/\s+/g, ' '))).size !== sourceMessages.length)
	fail('English source messages must remain unique after whitespace normalization');

const slugs = new Set();
for (const [locale, details] of locales) {
	if (!/^[a-z]{2}(?:-[A-Z]{2})?$/.test(locale)) fail(`invalid locale tag: ${locale}`);
	requireSafeText(details.name, `${locale} native name`);
	requireSafeText(details.ogLocale, `${locale} Open Graph locale`);
	if (!/^[a-z]{2}_[A-Z]{2}$/.test(details.ogLocale)) fail(`${locale} has an invalid Open Graph locale`);
	if (!safeSlug.test(details.slug) || reservedSlugs.has(details.slug))
		fail(`${locale} has an invalid or reserved URL slug`);
	if (slugs.has(details.slug)) fail(`duplicate URL slug: ${details.slug}`);
	slugs.add(details.slug);
	requireSafeText(catalogue.languageLabel[locale], `${locale} language-menu label`);
	const messages = catalogue.messages[locale];
	if (!Array.isArray(messages) || messages.length !== sourceMessages.length)
		fail(`${locale} must contain exactly ${sourceMessages.length} messages`);
	messages.forEach((message, index) => {
		requireSafeText(message, `${locale} message ${index}`);
	});
	for (const [index, message] of Object.entries(overrides[locale] ?? {})) {
		if (!/^\d+$/.test(index) || Number(index) >= sourceMessages.length)
			fail(`${locale} override index ${index} is invalid`);
		requireSafeText(message, `${locale} override ${index}`);
	}
}
for (const locale of Object.keys(overrides)) {
	if (!catalogue.locales[locale]) fail(`overrides exist for unknown locale ${locale}`);
}
const sourceFaqItemCount = faqCatalogue.en.items.length;
for (const [locale] of locales) {
	const faq = faqCatalogue[locale];
	if (!faq || !Array.isArray(faq.items) || faq.items.length === 0) fail(`${locale} FAQ content is missing`);
	if (faq.items.length !== sourceFaqItemCount)
		fail(`${locale} must contain exactly ${sourceFaqItemCount} FAQ items`);
	for (const key of ['eyebrow', 'title', 'intro']) requireSafeText(faq[key], `${locale} FAQ ${key}`);
	for (const [index, item] of faq.items.entries()) {
		requireSafeText(item.question, `${locale} FAQ question ${index}`);
		requireSafeText(item.answer, `${locale} FAQ answer ${index}`);
	}
}
for (const locale of Object.keys(faqCatalogue)) {
	if (!catalogue.locales[locale]) fail(`FAQ content exists for unknown locale ${locale}`);
}
sourceMessages.forEach((message, index) => {
	const pattern = new RegExp(escapeRegExp(message).replace(/\s+/g, '\\s+'));
	if (!pattern.test(template)) fail(`English source message ${index} does not occur in the template`);
});

